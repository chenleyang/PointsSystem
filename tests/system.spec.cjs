const { test, expect } = require('@playwright/test');
const key = 'factory-points-v1';
test('客户建档、充值、消耗、余额校验与刷新持久化', async ({ page }) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'新增客户'}).click();
  await page.getByLabel('工厂名称 *').fill('测试服装厂');
  await page.getByLabel('联系电话 *').fill('13812345678');
  await page.getByLabel('机器数量 *').fill('8');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'测试服装厂'});
  await expect(row).toBeVisible();
  await row.getByRole('button',{name:'充值',exact:true}).click();
  await page.getByRole('button',{name:'优享套餐 · ¥500'}).click();
  await expect(page.getByLabel('到账积分（含赠送）')).toHaveValue('5500');
  await page.getByRole('button',{name:'确认充值',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'确认充值',exact:true}).click();
  await page.getByRole('link',{name:'积分消耗',exact:true}).click();
  await page.getByLabel('消耗积分',{exact:true}).fill('6000');
  await page.getByLabel('消耗用途').fill('设备维护');
  await page.getByRole('button',{name:'确认消耗',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('积分不足');
  await page.getByLabel('消耗积分',{exact:true}).fill('500');
  await page.getByRole('button',{name:'确认消耗',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'确认消耗',exact:true}).click();
  await page.reload();
  const saved=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  const c=saved.customers.find(c=>c.name==='测试服装厂');
  expect(c.points).toBe(5000);
  expect(saved.transactions.filter(t=>t.customerId===c.id).map(t=>t.delta)).toEqual([5500,-500]);
  await page.getByRole('link',{name:'积分变动明细',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:'设备维护'})).toBeVisible();
  expect(errors).toEqual([]);
});
test('备份校验、导出与恢复', async ({ page }) => {
  await page.goto('/#backup');
  const original=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载完整备份'}).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/\.json$/);
  const invalid=structuredClone(original);invalid.customers[0].points++;
  await page.locator('#import-file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))});
  await expect(page.locator('#toast')).toContainText('余额与流水不一致');
  await page.getByRole('button',{name:'清空客户与流水',exact:true}).click();
  const password=page.getByLabel('清空密码',{exact:true});
  await expect(password).toHaveAttribute('type','password');
  await page.getByRole('button',{name:'确认清空',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key)).toEqual(original);
  await password.fill('wrong-password');
  await page.getByRole('button',{name:'确认清空',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('密码错误');
  expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key)).toEqual(original);
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'清空客户与流水',exact:true}).click();
  await expect(password).toHaveValue('');
  await password.fill('88888888');
  await page.getByRole('button',{name:'确认清空',exact:true}).click();
  expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).customers.length,key)).toBe(0);
  const cleared=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  expect(cleared.transactions).toEqual([]);
  expect(cleared.settings).toEqual(original.settings);
  expect(cleared.packages).toEqual(original.packages);
  expect(cleared.categories).toEqual(original.categories);
  await page.locator('#import-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(original))});
  await page.getByRole('button',{name:'覆盖并恢复'}).click();
  expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).customers.length,key)).toBe(6);
});
