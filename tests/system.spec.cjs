test('旧窗口不能覆盖另一个窗口更新的数据', async ({ page, context }) => {
  await page.goto('/#settings');
  const other=await context.newPage();
  await other.goto('/#settings');
  await other.getByLabel('系统名称',{exact:true}).fill('新的系统名称');
  await other.getByRole('button',{name:'保存设置'}).click();
  await page.getByLabel('系统名称',{exact:true}).fill('旧窗口覆盖');
  await page.getByRole('button',{name:'保存设置'}).click();
  await expect(page.getByRole('status')).toContainText('其他窗口变更');
  expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).settings.title,key)).toBe('新的系统名称');
});
